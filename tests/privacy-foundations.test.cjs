test('presence and typing preferences gate outgoing signals, including background tabs', () => {
  document.visibilityState = 'visible';
  let bus = typingBus('room', 'me', () => {}, { sharePresence: false, shareTyping: false });
  assert.equal(currentChannel.tracks, 0); assert.equal(currentChannel.untracks, 1);
  bus.ping(); assert.equal(currentChannel.sends, 0); bus.stop(); assert.equal(listener, null);
  bus = typingBus('room', 'me', () => {}, { sharePresence: true, shareTyping: true });
  assert.equal(currentChannel.tracks, 1); bus.ping(); assert.equal(currentChannel.sends, 1);
  document.visibilityState = 'hidden'; listener(); bus.ping();
  assert.equal(currentChannel.untracks, 1); assert.equal(currentChannel.sends, 1);
  document.visibilityState = 'visible'; listener(); assert.equal(currentChannel.tracks, 2);
  bus.stop(); assert.equal(listener, null);
});

