test('crypto refuses to create weak hashes but still verifies legacy records', async () => {
  const crypto = require('../lib/crypto.ts');
  const original = Object.getOwnPropertyDescriptor(globalThis, 'crypto');
  Object.defineProperty(globalThis, 'crypto', { value: undefined, configurable: true });
  try {
    assert.throws(() => crypto.newSalt(), /Secure randomness/);
    await assert.rejects(crypto.hashSecret('password', 'salt'), /Secure cryptography/);
    // Value generated by the old fallback for this exact secret and salt.
    let h1 = 0x811c9dc5, h2 = 0x01000193, s = 'salt::password';
    for (let i = 0; i < s.length; i++) { h1 = (h1 ^ s.charCodeAt(i)) * 16777619 >>> 0; h2 = (h2 + s.charCodeAt(i) * (i + 7)) >>> 0; }
    const legacy = `fb$${h1.toString(16)}${h2.toString(16)}${s.length.toString(16)}`;
    assert.equal(await crypto.verifySecret('password', 'salt', legacy), true);
    assert.equal(await crypto.verifySecret('wrong', 'salt', legacy), false);
  } finally { Object.defineProperty(globalThis, 'crypto', original); }
});

